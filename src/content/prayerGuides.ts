// ── Guide builder ────────────────────────────────────────────────────────────

interface GuideConfig {
  /** Prayer name in Arabic, e.g. "الفجر" */
  nameAr: string;
  /** Rak'ah count phrase for the intention, e.g. "أربعَ ركعات" */
  rakaatWord: string;
  /** How al-Fātiḥah is recited (aloud/quietly) in this prayer */
  fatihaMode: string;
  /** Body of the short-surah step (with examples) */
  surahBody: string;
  /** Body of the remaining-rak'ahs step (structure of this prayer) */
  remainingBody: string;
  /** First tashahhud exists only in prayers of 3+ rak'ahs */
  withFirstTashahhud: boolean;
}

function buildSteps(cfg: GuideConfig): PrayerGuideStep[] {
  const steps: PrayerGuideStep[] = [
    {
      title: 'النية',
      body: `قِف مستقبلًا القبلة بقلبٍ حاضر، وانوِ بقلبك أداء صلاة ${cfg.nameAr} ${cfg.rakaatWord} لله تعالى. النية محلُّها القلب، ولا يُشرع التلفّظ بها؛ يكفي أن تستشعر أنك واقف بين يدي الله.`,
    },
    {
      title: 'تكبيرة الإحرام',
      body: 'ارفع يديك حَذوَ منكبيك، وأصابعك ممدودة باتجاه القبلة، ثم كبِّر تكبيرة الإحرام؛ فبها تدخل في صلاتك وتنقطع عمّا سواها.',
      recitation: TAKBIR,
    },
    {
      title: 'دعاء الاستفتاح',
      body: 'ضع كفَّك اليمنى على اليسرى فوق صدرك، واقرأ دعاء الاستفتاح سرًّا؛ وهو سنّة مستحبّة تفتتح بها مناجاتك لربّك.',
      recitation: ISTIFTAH,
    },
    {
      title: 'قراءة الفاتحة',
      body: `استعذ بالله من الشيطان الرجيم، ثم اقرأ سورة الفاتحة ${cfg.fatihaMode}، وهي ركنٌ في كل ركعة؛ رتِّلها بتُؤَدةٍ وخشوع، وقل بعد ختامها: آمين.`,
      recitation: FATIHA,
    },
    {
      title: 'قراءة سورة قصيرة',
      body: cfg.surahBody,
    },
    {
      title: 'الركوع',
      body: 'كبِّر رافعًا يديك، ثم اركع واضعًا كفّيك على ركبتيك، وسوِّ ظهرك واطمئنّ، وقل ثلاث مرات:',
      recitation: TASBIH_RUKU,
    },
    {
      title: 'الرفع من الركوع',
      body: 'ارفع من الركوع قائلًا: «سَمِعَ اللهُ لِمَنْ حَمِدَهُ»، فإذا اعتدلت قائمًا فقل: «رَبَّنَا وَلَكَ الْحَمْدُ»، واطمئنّ في قيامك ولا تتعجّل.',
      recitation: RAF_MIN_RUKU,
    },
    {
      title: 'السجود',
      body: 'كبِّر واسجد على أعضائك السبعة: الجبهة مع الأنف، والكفّين، والركبتين، وأطراف القدمين. اطمئنّ في سجودك — فأقرب ما يكون العبد من ربه وهو ساجد — وقل ثلاث مرات:',
      recitation: TASBIH_SUJUD,
    },
    {
      title: 'الجلسة بين السجدتين',
      body: 'ارفع رأسك من السجود مكبِّرًا، واجلس مطمئنًّا وقل: «رَبِّ اغْفِرْ لِي»، ثم كبِّر واسجد السجدة الثانية كما فعلت في الأولى. وبهذا تكون قد أتممت الركعة الأولى.',
      recitation: BAYNA_SAJDATAYN,
    },
    {
      title: 'باقي الركعات',
      body: cfg.remainingBody,
    },
  ];

  if (cfg.withFirstTashahhud) {
    steps.push({
      title: 'التشهد الأول',
      body: 'بعد السجدة الثانية من الركعة الثانية اجلس مفترشًا، وضع كفّيك على فخذيك، وأشر بسبّابتك اليمنى، واقرأ التشهد، ثم انهض مكبِّرًا لإتمام ما بقي من صلاتك.',
      recitation: TASHAHHUD,
    });
  }

  steps.push(
    {
      title: 'التشهد الأخير والصلاة الإبراهيمية',
      body: 'في آخر ركعة، بعد السجدة الثانية، اجلس للتشهد الأخير — متورِّكًا إن تيسّر لك — واقرأ التحيات ثم الصلاة الإبراهيمية، ثم استعذ بالله من عذاب جهنم وعذاب القبر ومن فتنة المحيا والممات ومن فتنة المسيح الدجال، وادعُ بما أحببت من خيرَي الدنيا والآخرة.',
      recitation: `${TASHAHHUD}.\n\n${SALAT_IBRAHIMIYYA}.`,
    },
    {
      title: 'التسليم',
      body: 'التفت برأسك إلى جهة اليمين قائلًا: «السَّلَامُ عَلَيْكُمْ وَرَحْمَةُ اللهِ»، ثم إلى جهة اليسار قائلًا مثلها. وبهذا تمّت صلاتك؛ تقبّل الله منك.',
      recitation: TASLEEM,
    },
  );

  return steps;
}

