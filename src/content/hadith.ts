export function getDailyHadith(date = new Date()): HadithItem {
  const dayOfYear = Math.floor(
    (date.getTime() - new Date(date.getFullYear(), 0, 0).getTime()) / 86400000
  );
  return HADITH_ITEMS[dayOfYear % HADITH_ITEMS.length];
}

/** Previous days' items (most recent first) for the archive list. */
export function getArchive(days: number, from = new Date()): { item: HadithItem; date: Date }[] {
  const result: { item: HadithItem; date: Date }[] = [];
  for (let i = 1; i <= days; i++) {
    const date = new Date(from.getFullYear(), from.getMonth(), from.getDate() - i);
    result.push({ item: getDailyHadith(date), date });
  }
  return result;
}
